"""Tests for plugins/devflow/scripts/flow-copilot.py, the generated GitHub Copilot pack.

Renders into temp dirs only. Checks: every skill and agent is emitted with frontmatter valid
for Copilot, Claude tools map to Copilot aliases (read-only roles never get `edit`), output is
deterministic, `check` catches drift and passes after regeneration, no hook is emitted,
Copilot-specific text has no secret wording, and the Claude sources are untouched.
"""

import hashlib
import importlib.util
import json
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "plugins/devflow"
SCRIPT = PLUGIN / "scripts/flow-copilot.py"
# The pack ships no hooks, so the hook-installer skill is left out.
SKILLS = sorted(p.parent.name for p in PLUGIN.glob("skills/*/SKILL.md")
                if p.parent.name != "flow-hooks")
AGENTS = sorted(p.stem for p in PLUGIN.glob("agents/flow-*.md"))
COPILOT_ALIASES = {"read", "edit", "execute", "search", "web", "agent", "todo"}
SKILL_KEYS = {"name", "description", "license", "disable-model-invocation"}
AGENT_KEYS = {"name", "description", "tools"}
SECRET_WORDING = re.compile(r"\.env|secret|credential", re.I)


def run(*args):
    return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True)


def render(repo):
    result = run("render", "--repo", str(repo))
    assert result.returncode == 0, result.stdout + result.stderr
    return result


def frontmatter(path):
    """Parse the generated frontmatter: `key: value` lines; values are JSON scalars/lists
    (the generator quotes every string as JSON, which is also valid YAML) or bare words."""
    text = path.read_text(encoding="utf-8")
    assert text.startswith("---\n"), path
    head, _, body = text[4:].partition("\n---\n")
    values = {}
    for line in head.splitlines():
        key, sep, raw = line.partition(": ")
        assert sep, f"{path}: bad frontmatter line {line!r}"
        try:
            values[key] = json.loads(raw)
        except json.JSONDecodeError:
            values[key] = raw
    return values, body


def tree_digest(root):
    return {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file() and "__pycache__" not in p.parts}


def role_sets():
    source = (PLUGIN / "scripts/flow-agent.py").read_text(encoding="utf-8")
    m = re.search(r"^READ_ONLY_ROLES\s*=\s*\{([^}]*)\}", source, re.M | re.S)
    return {c.strip().strip('"') for c in m.group(1).split(",") if c.strip()}


def claude_tools(agent):
    text = (PLUGIN / f"agents/{agent}.md").read_text(encoding="utf-8")
    line = re.search(r"^tools:\s*(.+)$", text, re.M).group(1)
    return {t.strip() for t in line.split(",")}


class RenderedPack(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.repo = Path(cls.tmp.name)
        cls.before = tree_digest(PLUGIN)
        render(cls.repo)
        cls.gh = cls.repo / ".github"

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_claude_sources_untouched(self):
        self.assertEqual(self.before, tree_digest(PLUGIN))

    def test_every_skill_emitted_with_valid_frontmatter(self):
        emitted = sorted(p.parent.name for p in self.gh.glob("skills/*/SKILL.md"))
        self.assertEqual(SKILLS, emitted)
        for name in SKILLS:
            fm, body = frontmatter(self.gh / f"skills/{name}/SKILL.md")
            self.assertEqual(name, fm["name"])
            self.assertRegex(name, r"^[a-z0-9]+(-[a-z0-9]+)*$")
            self.assertTrue(fm["description"].strip(), name)
            self.assertLessEqual(set(fm), SKILL_KEYS, name)
            self.assertIn("generated by DevFlow", body.splitlines()[0])

    def test_explicit_only_skills_keep_flag(self):
        for name in SKILLS:
            src = (PLUGIN / f"skills/{name}/SKILL.md").read_text(encoding="utf-8")
            head = src.split("\n---\n", 1)[0]
            flagged = bool(re.search(r"^disable-model-invocation: true$", head, re.M))
            fm, _ = frontmatter(self.gh / f"skills/{name}/SKILL.md")
            self.assertEqual(flagged, fm.get("disable-model-invocation") is True, name)

    def test_skill_body_is_source_body(self):
        for name in SKILLS:
            src = (PLUGIN / f"skills/{name}/SKILL.md").read_text(encoding="utf-8")
            src_body = src[4:].partition("\n---\n")[2]
            _, body = frontmatter(self.gh / f"skills/{name}/SKILL.md")
            body = body.split("\n", 1)[1]  # drop the generated marker line
            self.assertEqual(re.sub(r"(\{devflow_root\}/agents/flow-[\w*-]+)\.md",
                                    r"\1.agent.md", src_body), body, name)

    def test_every_agent_emitted_with_valid_frontmatter(self):
        emitted = sorted(p.name.removesuffix(".agent.md")
                         for p in self.gh.glob("agents/*.agent.md"))
        self.assertEqual(AGENTS, emitted)
        for agent in AGENTS:
            fm, body = frontmatter(self.gh / f"agents/{agent}.agent.md")
            self.assertEqual(agent, fm["name"])
            self.assertTrue(fm["description"].strip())
            self.assertLessEqual(set(fm), AGENT_KEYS, agent)
            self.assertIsInstance(fm["tools"], list)
            self.assertLessEqual(set(fm["tools"]), COPILOT_ALIASES, agent)
            self.assertLessEqual(len(body), 30000, agent)

    def test_tool_mapping(self):
        read_only = role_sets()
        for agent in AGENTS:
            fm, _ = frontmatter(self.gh / f"agents/{agent}.agent.md")
            tools, src = set(fm["tools"]), claude_tools(agent)
            self.assertIn("read", tools, agent)
            self.assertEqual(bool(src & {"Write", "Edit"}), "edit" in tools, agent)
            self.assertEqual("Bash" in src, "execute" in tools, agent)
            self.assertEqual(bool(src & {"Grep", "Glob"}), "search" in tools, agent)
            self.assertEqual(bool(src & {"WebFetch", "WebSearch"}), "web" in tools, agent)
            if agent.removeprefix("flow-") in read_only:
                self.assertNotIn("edit", tools, agent)
        fm, _ = frontmatter(self.gh / "agents/flow-plan-checker.agent.md")
        self.assertEqual(["read", "search"], fm["tools"])
        fm, _ = frontmatter(self.gh / "agents/flow-executor.agent.md")
        self.assertEqual(["read", "edit", "execute", "search", "web"], fm["tools"])

    def test_devflow_root_paths_resolve_in_vendored_pack(self):
        # A vendored skill's devflow_root is `../..` from its SKILL.md, i.e. `.github`.
        missing = set()
        for md in self.gh.rglob("*.md"):
            for ref in re.findall(r"\{devflow_root\}/([\w./*<>-]+)", md.read_text(encoding="utf-8")):
                ref = re.sub(r"<[^>]*>.*$", "", ref.rstrip("."))  # `<name>` placeholder: its dir
                if not (self.gh / ref).exists() and not list(self.gh.glob(ref)):
                    missing.add(ref)
        self.assertEqual(set(), missing)
        self.assertTrue((self.gh / "skills/flow-status/../../references/hosts.md").resolve().is_file())

    def test_no_hooks_emitted(self):
        self.assertFalse((self.gh / "hooks").exists())
        self.assertFalse((self.gh / "skills/flow-hooks").exists())
        self.assertFalse((self.gh / "templates/hooks").exists())
        files = [p for p in self.repo.rglob("*") if p.is_file()]
        self.assertFalse(any("hook" in p.name.lower() and p.suffix == ".json" for p in files))
        self.assertEqual([], [str(p.relative_to(self.repo)) for p in files
                              if "pretooluse" in p.read_text(encoding="utf-8").lower()])

    def test_copilot_specific_text_has_no_secret_wording(self):
        # Generator-authored text only; vendored skill/agent/reference bodies stay verbatim.
        texts = {
            "copilot-setup-steps.yml":
                (self.gh / "workflows/copilot-setup-steps.yml").read_text(encoding="utf-8"),
            "devflow-copilot.json keys": json.dumps(
                {k: v for k, v in json.loads((self.gh / "devflow-copilot.json")
                                             .read_text(encoding="utf-8")).items() if k != "files"}),
            "marker": (self.gh / "skills/flow-new/SKILL.md").read_text(encoding="utf-8")
                      .split("\n---\n", 1)[1].splitlines()[0],
            "flow-copilot.py": SCRIPT.read_text(encoding="utf-8"),
            "flow-copilot.py --help": run("--help").stdout,
        }
        for path, start, end in (("plugins/devflow/references/hosts.md", "## GitHub Copilot", "\n## "),
                                 ("docs/installation.md", "## GitHub Copilot", "\n## "),
                                 ("README.md", "### GitHub Copilot", "\n## "),
                                 ("CHANGELOG.md", "## 0.54.0", "\n## "),
                                 ("docs/getting-started-copilot.md", "# ", "\n# ")):
            text = (ROOT / path).read_text(encoding="utf-8")
            section = text[text.index(start):]
            texts[f"{path} {start}"] = section[:section.find(end, len(start)) % (len(section) + 1)]
        for label, text in texts.items():
            self.assertIsNone(SECRET_WORDING.search(text), label)
        # The cloud agent is not supported at this time, so the README does not offer it.
        self.assertNotIn("cloud", texts["README.md ### GitHub Copilot"].lower())
        self.assertFalse((self.gh / "copilot-instructions.md").exists())

    def test_setup_steps_single_named_job(self):
        text = (self.gh / "workflows/copilot-setup-steps.yml").read_text(encoding="utf-8")
        self.assertEqual(["copilot-setup-steps"], re.findall(r"^  ([\w-]+):\s*$",
                                                              text.split("\njobs:\n", 1)[1], re.M))
        self.assertIn("python", text)

    def test_no_prompt_files_or_instructions_overwrite(self):
        self.assertFalse((self.gh / "prompts").exists())
        self.assertFalse((self.gh / "copilot-instructions.md").exists())

    def test_marker_on_generated_text_files(self):
        version = json.loads((PLUGIN / ".claude-plugin/plugin.json").read_text())["version"]
        for rel in ("skills/flow-new/SKILL.md", "agents/flow-verifier.agent.md",
                    "workflows/copilot-setup-steps.yml"):
            text = (self.gh / rel).read_text(encoding="utf-8")
            self.assertIn(f"generated by DevFlow {version} — do not edit", text, rel)
        for name in SKILLS:
            marker = (self.gh / f"skills/{name}/SKILL.md").read_text(encoding="utf-8")
            self.assertIn("in this pack {devflow_root} is .github -->",
                          marker.split("\n---\n", 1)[1].splitlines()[0], name)
        manifest = json.loads((self.gh / "devflow-copilot.json").read_text(encoding="utf-8"))
        self.assertEqual(version, manifest["version"])


class Determinism(unittest.TestCase):
    def test_two_renders_are_byte_identical(self):
        with tempfile.TemporaryDirectory() as a, tempfile.TemporaryDirectory() as b:
            render(Path(a))
            render(Path(b))
            self.assertEqual(tree_digest(Path(a)), tree_digest(Path(b)))


class DriftCheck(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = Path(self.tmp.name)
        render(self.repo)

    def check(self, script=SCRIPT):
        return subprocess.run([sys.executable, str(script), "check", "--repo", str(self.repo)],
                              capture_output=True, text=True)

    def test_check_passes_fresh_fails_on_edit_passes_after_regen(self):
        self.assertEqual(0, self.check().returncode)
        skill = self.repo / ".github/skills/flow-plan/SKILL.md"
        skill.write_text(skill.read_text(encoding="utf-8") + "hand edit\n", encoding="utf-8")
        result = self.check()
        self.assertEqual(1, result.returncode)
        self.assertIn(".github/skills/flow-plan/SKILL.md", result.stdout)
        refused = run("render", "--repo", str(self.repo))
        self.assertEqual(1, refused.returncode)
        self.assertIn(".github/skills/flow-plan/SKILL.md", refused.stderr)
        self.assertTrue(skill.read_text(encoding="utf-8").endswith("hand edit\n"))
        self.assertEqual(0, run("render", "--repo", str(self.repo), "--force").returncode)
        self.assertEqual(0, self.check().returncode)

    def test_check_fails_on_deleted_file(self):
        (self.repo / ".github/agents/flow-reviewer.agent.md").unlink()
        self.assertEqual(1, self.check().returncode)

    def test_vendored_copy_checks_integrity_without_sources(self):
        vendored = self.repo / ".github/scripts/flow-copilot.py"
        self.assertEqual(0, self.check(vendored).returncode)
        ref = self.repo / ".github/references/hosts.md"
        ref.write_text("tampered\n", encoding="utf-8")
        result = self.check(vendored)
        self.assertEqual(1, result.returncode)
        self.assertIn(".github/references/hosts.md", result.stdout)

    def test_manifest_path_outside_github_is_refused(self):
        victim = self.repo / "src/app.py"
        victim.parent.mkdir()
        victim.write_text("keep\n", encoding="utf-8")
        manifest_path = self.repo / ".github/devflow-copilot.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        manifest["files"]["src/app.py"] = hashlib.sha256(b"keep\n").hexdigest()
        manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
        for args in (("render", "--repo", str(self.repo)), ("check", "--repo", str(self.repo))):
            result = run(*args)
            self.assertEqual(1, result.returncode, args)
            self.assertIn("refusing path outside .github/", result.stderr)
        self.assertEqual("keep\n", victim.read_text(encoding="utf-8"))

    def test_quoted_or_block_frontmatter_values_are_refused(self):
        spec = importlib.util.spec_from_file_location("flow_copilot", SCRIPT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        self.assertEqual("plain - text", module.scalar({"d": "plain - text"}, "d", "x"))
        for value in ('"Run X: then Y"', "'quoted'", ">-", "|", ""):
            with self.assertRaises(SystemExit):
                module.scalar({"d": value}, "d", "x")

    def test_crlf_checkout_is_not_drift(self):
        # Git for Windows (autocrlf) checks text out as CRLF; that is not a hand edit.
        for rel in (".github/skills/flow-plan/SKILL.md", ".github/references/hosts.md"):
            path = self.repo / rel
            path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
        self.assertEqual(0, self.check().returncode)
        self.assertEqual(0, self.check(self.repo / ".github/scripts/flow-copilot.py").returncode)
        self.assertEqual(0, run("render", "--repo", str(self.repo)).returncode)

    def test_symlink_out_of_github_is_refused(self):
        with tempfile.TemporaryDirectory() as outside:
            refs = self.repo / ".github/references"
            shutil.rmtree(refs)
            refs.symlink_to(outside, target_is_directory=True)
            result = run("render", "--repo", str(self.repo), "--force")
            self.assertEqual(1, result.returncode)
            self.assertIn("resolves outside .github/", result.stderr)
            self.assertEqual([], list(Path(outside).iterdir()))

    def test_refuses_to_overwrite_unowned_file(self):
        with tempfile.TemporaryDirectory() as other:
            target = Path(other) / ".github/workflows/copilot-setup-steps.yml"
            target.parent.mkdir(parents=True)
            target.write_text("mine\n", encoding="utf-8")
            result = run("render", "--repo", other)
            self.assertEqual(1, result.returncode)
            self.assertIn("copilot-setup-steps.yml", result.stderr)
            self.assertEqual("mine\n", target.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
